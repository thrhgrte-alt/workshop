def write_places(specs: dict) -> None:
    (P.root / "projects.yaml").write_text(REGISTRY, encoding="utf-8")
    for pid, plid, name in (("demo_mine", "main", "balanced"), ("demo_mine", "hardcore", "balanced"), ("demo_tycoon", "main", "runaway")):
        d = P.root / "projects" / pid / plid
        d.mkdir(parents=True, exist_ok=True)
        sp = copy.deepcopy(specs[name])
        sp["id"] = f"{pid}_{plid}"
        (d / "economy.yaml").write_text(HEADER.replace("toy economy", f"toy economy for the SYNTHETIC place {pid}/{plid}") + S.dump_yaml(sp), encoding="utf-8")
    (P.root / "projects" / "demo_mine" / "hardcore" / "bands.yaml").write_text(HARDCORE_BANDS, encoding="utf-8")


def main() -> None:
    specs = {"balanced": balanced(), "wall": wall(), "runaway": runaway(), "dominant": dominant()}
    ctxs, results = {}, {}
    for name, spec in specs.items():
        write_yaml(name, spec)
        ctxs[name] = ctx_of(spec)
        results[name] = A.check(ctxs[name])
    # a proposal for the wall, kept as an example of an accepted rebalance (generated by the tool, not by hand)
    base = results["wall"]
    target = R.select_finding(base["findings"], "wall", upgrade="drill_4", archetype="regular")
    prop = R.propose(ctxs["wall"], base, target, max_changes=1)
    assert prop["found"], prop
    fixed = R.apply_to_raw(specs["wall"], prop["changes"])
    fixed["id"] = "wall_rebalanced"
    fixed["name"] = "Toy economy with the wall fixed by propose_rebalance"
    write_yaml("wall_rebalanced", fixed)
    after = A.check(ctx_of(fixed))
    (EX / "imports").mkdir(parents=True, exist_ok=True)
    (EX / "imports" / "sample_dump.json").write_text(json.dumps(SAMPLE_DUMP, indent=2) + "\n", encoding="utf-8")
    (EX / "playtest").mkdir(parents=True, exist_ok=True)
    note = {"request": "Playtest note on the wall toy: tier 4 felt too slow", "decision": "revise", "reason": "tier 4 felt too slow",
            "corrections": [{"dimension": "pacing", "direction": "less", "felt": "too_slow", "tier": 4, "archetype": "regular", "note": "tier 4 felt too slow"}]}
    (EX / "playtest" / "tier4_felt_slow.json").write_text(json.dumps(note, indent=2) + "\n", encoding="utf-8")
    # projects and places (all SYNTHETIC): one registry, one folder per place
    write_places(specs)
    # plots
    for name in specs:
        plot.render(ctxs[name].sims(), EX / ("positive" if name == "balanced" else "negative") / f"{name}.png", title=f"{specs[name]['name']}")

    def codes(res, sev=("error", "warning")):
        return sorted({f["code"] for f in res["findings"] if f["severity"] in sev})

    def meas(res):
        m = res["metrics"]
        return {k: round(m[k], 3) for k in sorted(m)}

    rows = []

    def entry(eid, kind, title, path, polarity, desc, tags, domain, preview=None, notes=None, rating=None, status="curated", origin="synthetic-example"):
        row = {"id": eid, "kind": kind, "title": title, "path": path, "description": desc, "application": {"name": "Roblox Studio", "version": "none (no Studio involved)"},
               "license": LIC, "provenance": {"origin": origin, "creator": "econbal example generator"}, "tags": tags, "status": status, "polarity": polarity, "domain": domain}
        if preview:
            row["preview"] = preview
        if notes:
            row["correction_notes"] = notes
        if rating is not None:
            row["rating"] = rating
        return row

    dom = lambda name, res: {"spec_file": f"examples/economies/{name}.yaml", "expected_verdict": res["verdict"], "expected_codes": codes(res), "days": specs[name]["simulation"]["days"],
                              "seed": 0, "measurements": meas(res)}
    rows.append(entry("econ-balanced", "economy_spec", "Balanced toy economy", "examples/economies/balanced.yaml", "positive",
                      "Ten tiers whose regular-player steps (10,10,10,20,30,40,60,80,100,120 active minutes) sit inside the placeholder bands, a rebirth loop that keeps content from running out, a tie-break choice at tier 4, boosts under 3x. Passes every check.",
                      ["balanced", "ladder", "rebirth", "boosts"], dom("balanced", results["balanced"]), "examples/positive/balanced.png", rating=5))
    rows.append(entry("econ-wall", "economy_spec", "Toy economy with a wall (avoid)", "examples/economies/wall.yaml", "negative",
                      "AVOID: drill_4 costs 32000 against an income of 80 per minute, so regular players wait 400 active minutes. Flagged as wall, cost_cliff, gap_cliff.",
                      ["wall", "cost-cliff"], dom("wall", results["wall"]), "examples/negative/wall.png", notes=["wall: lower the cost of the step or add income before it", "cost: keep each step within 5x of the previous"]))
    rows.append(entry("econ-runaway", "economy_spec", "Toy economy with runaway currency (avoid)", "examples/economies/runaway.yaml", "negative",
                      "AVOID: income 100 per minute against costs 100, 300 and 900. Everything is bought within minutes and the currency floods. Flagged as under_band, content_exhausted, runaway_inflation.",
                      ["inflation", "runaway"], dom("runaway", results["runaway"]), "examples/negative/runaway.png", notes=["inflation: add sinks or content", "pacing: steps must take 5-15 minutes early on"]))
    rows.append(entry("econ-dominant", "economy_spec", "Toy economy with a dominant option (avoid)", "examples/economies/dominant.yaml", "negative",
                      "AVOID: at tiers 2 and 3 option A costs the same as option B and gives twice the income, so the choice is not a choice. Flagged as dominant_option, dominated_option, dominant_strategy.",
                      ["dominant", "choice"], dom("dominant", results["dominant"]), "examples/negative/dominant.png", notes=["dominant_option: make the alternatives trade off"]))
    rows.append(entry("rebalance-wall-001", "rebalance", "Wall fixed by a one-value change", "examples/economies/wall_rebalanced.yaml", "positive",
                      "propose_rebalance (max_changes=1) found the smallest change on its search grid that removes the wall at drill_4 without creating a new warning: "
                      + "; ".join(f"{c['path']} {c['before']} -> {c['after']}" for c in prop["changes"]) + ". Generated by the tool, not by hand.",
                      ["rebalance", "wall", "accepted"], {"spec_file": "examples/economies/wall_rebalanced.yaml", "expected_verdict": after["verdict"], "expected_codes": codes(after),
                                                           "days": 14, "seed": 0, "changes": [{"path": c["path"], "before": c["before"], "after": c["after"]} for c in prop["changes"]],
                                                           "measurements": meas(after)}, rating=4))
    rows.append(entry("playtest-tier4-slow", "playtest_note", "Playtest note: tier 4 felt too slow", "examples/playtest/tier4_felt_slow.json", "positive",
                      "A synthetic playtest note in the shape that suggest_band_adjustments reads: dimension pacing, tier 4, regular archetype, felt too_slow. Not a real playtest.",
                      ["playtest", "pacing"], {"seed": 0}))
    rows.append({"id": "econ-unreviewed-import", "kind": "economy_spec", "title": "Unreviewed import", "path": "examples/imports/sample_dump.json", "license": {"owner": "unknown"},
                 "provenance": {"origin": "user-supplied"}, "tags": ["import"], "status": "candidate", "polarity": "positive"})
    out = EX / "library" / "assets.jsonl"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(json.dumps(r, sort_keys=True) for r in rows) + "\n", encoding="utf-8")
    print(f"wrote {len(rows)} library entries")
    for n, r in results.items():
        print(n, r["verdict"], codes(r))
    print("wall fix:", prop["changes"])


if __name__ == "__main__":
    main()
