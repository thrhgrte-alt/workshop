#!/usr/bin/env python3
"""Regenerate the tracked SYNTHETIC examples: four hand-built toy economies, a sample import dump, plots and examples/library/assets.jsonl.

The toys are small enough to check on paper (the numbers are chosen so every purchase minute of the 'regular' archetype is an exact integer):

* balanced  - one ladder of 10 tiers, income doubles at each step (r_n = 10 * 2^n per minute for 'regular'), step cost = income x wanted minutes,
              a rebirth after tier 10, two boosts. Wanted minutes per tier: 10,10,10,20,30,40,60,80,100,120 (inside the placeholder bands).
* wall      - the same ladder, but tier 4 costs 32000 instead of 1600: a 400 minute wall.
* runaway   - three tiers that cost almost nothing against an income of 100/min: everything is bought in minutes and the currency floods.
* dominant  - the balanced ladder with tier 2 and tier 3 turned into choices where option A has the same cost and twice the income of option B.
"""
import copy
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from econbal import project  # noqa: E402
from guide_core.style import load_style  # noqa: E402
from econbal.domain import analysis as A, plot, rebalance as R, spec as S  # noqa: E402

P = project()
EX = P.root / "examples"
HEADER = "# SYNTHETIC toy economy generated by scripts/make_examples.py. Not a real game. See examples/positive and examples/negative.\n"
LIC = {"owner": "user", "spdx": "MIT", "notes": "Synthetic example generated by scripts/make_examples.py"}

WANTED_MINUTES = [10, 10, 10, 20, 30, 40, 60, 80, 100, 120]
ARCHETYPES = {
    "casual": {"session_minutes": 15, "sessions_per_day": 2, "efficiency": 0.8, "variance": 0.0, "boosts": []},
    "regular": {"session_minutes": 20, "sessions_per_day": 3, "efficiency": 1.0, "variance": 0.0, "boosts": []},
    "grinder": {"session_minutes": 60, "sessions_per_day": 4, "efficiency": 1.5, "variance": 0.0, "boosts": []},
}


def ladder(minutes=WANTED_MINUTES, base=10):
    """(cost, add) per tier: add = income before the step (income doubles), cost = income before x wanted minutes."""
    rows, rate = [], base
    for m in minutes:
        rows.append((rate * m, rate))
        rate *= 2
    return rows


def base_spec(sid: str, name: str, desc: str, rows, *, days=14, with_rebirth=True, boosts=True) -> dict:
    spec = {
        "format": S.FORMAT, "id": sid, "name": name, "description": desc,
        "simulation": {"days": days, "seed": 0, "policy": "cheapest_payback"},
        "currencies": {"coins": {"start": 0}},
        "sources": [{"id": "mining", "currency": "coins", "per_minute": 10}],
        "sinks": [],
        "upgrades": [{"id": f"drill_{i + 1}", "track": "drill", "tier": i + 1, "currency": "coins", "cost": c,
                      "effects": [{"source": "mining", "add": a}]} for i, (c, a) in enumerate(rows)],
        "boosts": ([{"id": "double_income", "kind": "gamepass", "price_robux": 399, "effects": [{"source": "*", "mult": 2}]},
                    {"id": "lucky_ore", "kind": "gamepass", "price_robux": 199, "effects": [{"source": "mining", "mult": 1.25}]}] if boosts else []),
        "archetypes": copy.deepcopy(ARCHETYPES),
        "rebirths": ([{"id": "rebirth", "currency": "coins", "cost": 1024000, "resets": {"tracks": ["drill"], "currencies": ["coins"]},
                       "bonus": {"source": "*", "mult_per_rebirth": 0.5}, "max": 2}] if with_rebirth else []),
        "locked": [],
    }
    return spec


def balanced() -> dict:
    s = base_spec("balanced", "Balanced toy economy", "One 10-tier ladder; regular players wait 10-120 active minutes per step; one rebirth loop; two boosts.", ladder())
    # tier 4 becomes a real choice whose options TRADE OFF: same payback (20 minutes), different cost and income.
    s["upgrades"][3]["strategy"] = "speed"
    s["upgrades"].insert(4, {"id": "drill_4b", "track": "drill", "tier": 4, "currency": "coins", "cost": 2400, "effects": [{"source": "mining", "add": 120}], "strategy": "value"})
    s["upgrades"][3]["name"] = "drill_4 (cheap)"
    s["upgrades"][4]["name"] = "drill_4b (dear)"
    return s


def wall() -> dict:
    rows = ladder()
    rows[3] = (32000, rows[3][1])  # tier 4 costs 20x more than the balanced 1600
    s = base_spec("wall", "Toy economy with a wall", "Same ladder as 'balanced', but drill_4 costs 32000: regular players wait 400 active minutes for it.", rows)
    return s


def runaway() -> dict:
    rows = [(100, 100), (300, 200), (900, 400)]
    s = base_spec("runaway", "Toy economy with runaway currency", "Income 100 per minute against costs of 100, 300 and 900: everything is bought in minutes and nothing is left to spend on.", rows, boosts=False,
                  with_rebirth=False)
    s["sources"][0]["per_minute"] = 100
    return s


def dominant() -> dict:
    rows = ladder()
    s = base_spec("dominant", "Toy economy with a dominant option", "The balanced ladder, but tiers 2 and 3 are choices where option A costs the same as B and gives twice the income.",
                  rows, boosts=False)
    ups = []
    for u in s["upgrades"]:
        if u["tier"] in (2, 3):
            a = copy.deepcopy(u)
            a["strategy"] = "speed"
            b = copy.deepcopy(u)
            b["id"] = u["id"] + "b"
            b["effects"] = [{"source": "mining", "add": u["effects"][0]["add"] / 2}]
            b["strategy"] = "value"
            ups += [a, b]
        else:
            ups.append(u)
    s["upgrades"] = ups
    return s


def write_yaml(name: str, spec: dict) -> Path:
    path = EX / "economies" / f"{name}.yaml"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + S.dump_yaml(spec), encoding="utf-8")
    return path


def ctx_of(spec: dict) -> A.Ctx:
    errs = S.errors_of(S.validate(spec))
    assert not errs, errs
    return A.make_ctx(spec, load_style(P), A.load_rules(P.root))


